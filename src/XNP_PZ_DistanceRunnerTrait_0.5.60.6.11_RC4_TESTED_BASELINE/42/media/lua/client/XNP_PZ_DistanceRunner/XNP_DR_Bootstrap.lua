local function playerAt(index)
    if type(getSpecificPlayer) == "function" then
        return getSpecificPlayer(index or 0)
    end
    if type(getPlayer) == "function" then
        return getPlayer()
    end
    return nil
end

function Bootstrap.OnGameStart()
    local player = playerAt(0)
    if Core.GreenWorldOrb then Core.GreenWorldOrb.InitializePlayer(player, "GAME_START") end
    if Core.PhoenixLifeGate then Core.PhoenixLifeGate.InitializePlayer(player, "GAME_START") end
    if Core.PhoenixTransaction then Core.PhoenixTransaction.InitializePlayer(player, "GAME_START") end
    if Core.RoundMarkerMapVisibility then Core.RoundMarkerMapVisibility.Update(true) end
    -- Resolve Phoenix independently; this does not activate or alter the
    -- existing Distance Runner trait cache.
    if Core.PurplePhoenixTrait then
        Core.PurplePhoenixTrait.Refresh(player)
    end
    -- 0.5.60 protection state is transient and never survives into 0.5.60.1.
    if Core.PurplePhoenixInvulnerability then
        Core.PurplePhoenixInvulnerability.DiscardTransient("GAME_START_MIGRATION_RESET")
    end
    if Core.PurplePhoenixProtect then
        Core.PurplePhoenixProtect.DiscardTransient("GAME_START_MIGRATION_RESET")
    end
    if Core.ExtraTraits then
        Core.ExtraTraits.ResetCaches()
    end
    if Core.PurplePhoenixUI then
        Core.PurplePhoenixUI.Update(player)
    end
    if Core.GreenSkillUI then
        Core.GreenSkillUI.Update(player)
    end
    if Core.RedGuardianMark then
        Core.RedGuardianMark.GrantStarter(player)
    end
    if Core.RedMagicUI then
        Core.RedMagicUI.Update(player, true)
    end
    if Core.Runtime then
        Core.Runtime.ActivateForPlayer(player)
    end
end

function Bootstrap.OnCreatePlayer(player_index)
    local player = playerAt(player_index or 0)
    if Core.GreenWorldOrb then
        Core.GreenWorldOrb.Shutdown("PLAYER_REPLACED")
        Core.GreenWorldOrb.InitializePlayer(player, "CREATE_PLAYER")
    end
    if Core.RedGuardianMark then Core.RedGuardianMark.Cleanup("CREATE_PLAYER_REPLACEMENT") end
    if Core.PhoenixLifeGate then Core.PhoenixLifeGate.InitializePlayer(player, "CREATE_PLAYER") end
    if Core.PhoenixTransaction then Core.PhoenixTransaction.InitializePlayer(player, "CREATE_PLAYER") end
    if Core.PurplePhoenixInvulnerability then Core.PurplePhoenixInvulnerability.DiscardTransient("NEW_PLAYER") end
    if Core.PurplePhoenixProtect then Core.PurplePhoenixProtect.DiscardTransient("NEW_PLAYER") end
    if Core.RoundMarkerMapVisibility then Core.RoundMarkerMapVisibility.Update(true) end
    if Core.Trait then
        Core.Trait.ResetCache()
    end
    if Core.TraitRegistration then
        Core.TraitRegistration.ResetCache()
    end
    if Core.PurplePhoenixTraitRegistration then
        Core.PurplePhoenixTraitRegistration.ResetCache()
    end
    if Core.PurplePhoenixTrait then
        Core.PurplePhoenixTrait.ResetCache()
        Core.PurplePhoenixTrait.Refresh(player)
    end
    if Core.ExtraTraits then
        Core.ExtraTraits.ResetCaches()
    end
    if Core.PurplePhoenixUI then
        Core.PurplePhoenixUI.Update(player)
    end
    if Core.GreenSkillUI then
        Core.GreenSkillUI.Update(player)
    end
    if Core.RedGuardianMark then
        Core.RedGuardianMark.GrantStarter(player)
    end
    if Core.RedMagicUI then
        Core.RedMagicUI.Update(player, true)
    end
    if Core.Runtime then
        Core.Runtime.ActivateForPlayer(player)
    end
end

function Bootstrap.OnPlayerDeath(player)
    if Core.PhoenixLifeGate then Core.PhoenixLifeGate.MarkDead(player, "PLAYER_DEATH") end
    if Core.PurplePhoenixDamageGuard then Core.PurplePhoenixDamageGuard.CancelForDeath(player, "PLAYER_DEATH") end
    if Core.PurplePhoenixRevive then Core.PurplePhoenixRevive.CancelPendingForDeath(player, "PLAYER_DEATH") end
    if Core.PurplePhoenixState then Core.PurplePhoenixState.CancelPendingForDeath(player) end
    if Core.PurplePhoenixTrait then Core.PurplePhoenixTrait.ResetCache() end
    if Core.Trait then Core.Trait.ResetCache() end
    if Core.ExtraTraits then Core.ExtraTraits.ResetCaches() end
    if Core.Runtime then
        Core.Runtime.Cleanup("player_death", player)
    end
end

function Bootstrap.OnMainMenuEnter()
    if Core.Trait then
        Core.Trait.ResetCache()
    end
    if Core.PurplePhoenixTrait then
        Core.PurplePhoenixTrait.ResetCache()
    end
    if Core.PurplePhoenixTraitRegistration then
        Core.PurplePhoenixTraitRegistration.ResetCache()
    end
    if Core.ExtraTraits then
        Core.ExtraTraits.ResetCaches()
    end
    if Core.Runtime then
        Core.Runtime.Cleanup("main_menu")
    end
    if Core.PhoenixLifeGate then Core.PhoenixLifeGate.ResetSession() end
end

function Bootstrap.OnGameExit()
    if Core.Runtime then
        Core.Runtime.Cleanup("game_exit")
    end
    if Core.PhoenixLifeGate then Core.PhoenixLifeGate.ResetSession() end
end

function Bootstrap.RegisterEvents()
    -- Refresh the callback in place on Lua reload. The scheduler keeps one
    -- ordered task per stable ID, while the event gate below remains untouched.
    if Core.RedGuardianMark and Core.RedGuardianMark.RegisterSchedulerTask then
        Core.RedGuardianMark.RegisterSchedulerTask()
    end
    if Core.events_registered then
        return true
    end
    if Core.SandboxTuning then
        Core.SandboxTuning.Load()
    end
    if Events and Events.OnGameStart then
        Events.OnGameStart.Add(Bootstrap.OnGameStart)
    end
    if Events and Events.OnCreatePlayer then
        Events.OnCreatePlayer.Add(Bootstrap.OnCreatePlayer)
    end
    if Events and Events.OnPlayerUpdate and Core.Runtime then
        Events.OnPlayerUpdate.Add(Core.Runtime.Update)
        if Config.RUNTIME_UPDATE_REGISTRATION_LOGS then
            print("[XNP RUNTIME] update_registered=true event=OnPlayerUpdate")
        end
    end
    if Events and Events.OnPlayerDeath then
        Events.OnPlayerDeath.Add(Bootstrap.OnPlayerDeath)
    end
    if Events and Events.OnMainMenuEnter then
        Events.OnMainMenuEnter.Add(Bootstrap.OnMainMenuEnter)
    end
    if Events and Events.OnGameExit then
        Events.OnGameExit.Add(Bootstrap.OnGameExit)
    end
    if Core.PurplePhoenixDamageGuard then
        Core.PurplePhoenixDamageGuard.RegisterEvents()
    end
    if Core.RedGuardianMark then
        Core.RedGuardianMark.RegisterEvents()
    end
    Core.events_registered = true
    print("[XNP DR] BUILD_MARKER=" .. tostring(Constants.BUILD_ID))
    Constants.Log("loaded version=" .. Constants.VERSION .. " internal=" .. Constants.INTERNAL_VERSION .. " build=" .. Constants.BUILD_ID)
    if Core.LogThrottle then
        Core.LogThrottle.Startup()
    end
    logModuleStartup()
    return true
end

Core.Bootstrap = Bootstrap
Bootstrap.RegisterEvents()
return Bootstrap
